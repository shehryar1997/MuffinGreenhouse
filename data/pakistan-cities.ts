export const provinces = [...new Set(pakistanCities.map(city => city.province))]

// Helper to filter cities by province
export function getCitiesByProvince(province: string): PakistanCity[] {
  return pakistanCities.filter(city => city.province === province)
}

// Helper to search cities by name (case-insensitive)
export function searchCities(query: string): PakistanCity[] {
  const normalizedQuery = query.toLowerCase().trim()
  if (!normalizedQuery) return pakistanCities
  
  return pakistanCities.filter(city =>
    city.name.toLowerCase().includes(normalizedQuery)
  )
}
